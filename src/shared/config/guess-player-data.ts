function player(value: unknown[]): GuessPlayer {
  const [id, name, nationality, age, position, ...teams] = value
  const normalizedId = String(id)
  const listedTeams = teams.flatMap((team) =>
    Array.isArray(team) ? team.map(String) : [String(team)]
  )
  const careerTeams = [
    ...listedTeams,
    ...(EXTRA_CAREER_TEAMS[normalizedId] || []),
  ].filter((team, index, allTeams) => allTeams.indexOf(team) === index)
  return {
    id: normalizedId,
    name: String(name),
    nationality: String(nationality),
    age: Number(age),
    position: String(position),
    teams: careerTeams,
  }
}

